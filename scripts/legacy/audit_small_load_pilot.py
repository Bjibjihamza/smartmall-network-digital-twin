#!/usr/bin/env python3
"""Audit Phase 2.12a SMALL traffic pilot, without Mininet or dependencies.

Run from SmartMall project root (Windows Conda or Linux):
  python scripts/legacy/audit_small_load_pilot.py --pilot data/raw/small_v1/load_pilot_<id>

The audit distinguishes application-level verified iperf3 receiver rate from
Linux destination-host ingress counter rate (includes network/protocol overhead).
Neither offered iperf3 rate nor an iperf3 JSON summary with unknown sender/receiver
role is ever labeled as verified receiver throughput.
"""
import argparse
import csv
import json
import math
from collections import defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PATH_LINKS = ("L1", "L2", "L4", "L5")
COUNTERS = ("rx_bytes_delta", "tx_bytes_delta", "rx_packets_delta", "tx_packets_delta")


def rows(path):
    with path.open(newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def number(value):
    try:
        n = float(value)
        return n if math.isfinite(n) else None
    except (ValueError, TypeError):
        return None


def summary_rate(summary):
    if isinstance(summary, dict):
        bps = number(summary.get("bits_per_second"))
        if bps is not None:
            return bps / 1e6
    return None


def find_receiver_rate(raw):
    """Only trust data explicitly tagged receiver, never an unlabeled `end.sum`."""
    end = raw.get("end", {})
    for section in ("sum_received", "sum"):
        obj = end.get(section)
        if isinstance(obj, dict) and (section == "sum_received" or obj.get("sender") is False):
            rate = summary_rate(obj)
            if rate is not None:
                return rate, f"end.{section}"
    for item in end.get("streams", []):
        if not isinstance(item, dict):
            continue
        for typ in ("udp", "receiver", "sum_received"):
            obj = item.get(typ)
            if isinstance(obj, dict) and (typ != "udp" or obj.get("sender") is False):
                rate = summary_rate(obj)
                if rate is not None:
                    return rate, f"end.streams[].{typ}"
    server_json = raw.get("server_output_json")
    if isinstance(server_json, dict):
        server_end = server_json.get("end", {})
        for section in ("sum_received", "sum"):
            obj = server_end.get(section)
            if isinstance(obj, dict):
                rate = summary_rate(obj)
                if rate is not None:
                    # This is server-side output generated by receiver.
                    return rate, f"server_output_json.end.{section}"
    return None, "unverified"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pilot", type=Path, required=True,
                        help="Path to load_pilot_<id> directory")
    args = parser.parse_args()
    pilot = args.pilot.resolve()
    manifest_path = pilot / "manifest.json"
    if not manifest_path.exists():
        parser.error(f"Missing manifest.json at {pilot}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8-sig"))
    probes = rows(pilot / "icmp_telemetry.csv")
    ports = rows(pilot / "port_deltas.csv")
    profiles = manifest.get("profiles", [])
    expid = manifest.get("experiment_id", pilot.name)
    problems, warnings = [], []
    if manifest.get("status") != "completed":
        problems.append(f"Pilot status is {manifest.get('status')!r}, not completed")
    if manifest.get("topology_id") != "small_v1":
        problems.append("Topology is not small_v1")
    if not profiles:
        problems.append("No profiles in manifest")
    if len(probes) != 6 * len(profiles):
        problems.append(f"ICMP rows {len(probes)} != 6 * {len(profiles)}")
    if len(ports) != 12 * len(profiles):
        problems.append(f"Port rows {len(ports)} != 12 * {len(profiles)}")
    if any(r.get("experiment_id") != expid for r in probes + ports):
        problems.append("Experiment ID mismatch across files")

    icmp_by_profile = defaultdict(list)
    port_by_profile = defaultdict(list)
    for r in probes:
        icmp_by_profile[r.get("profile")].append(r)
    for r in ports:
        port_by_profile[r.get("profile")].append(r)

    table = []
    detail = []
    loads = []
    for profile in profiles:
        name = profile.get("profile")
        offered = number(profile.get("offered_mbps"))
        pings = icmp_by_profile.get(name, [])
        portrows = port_by_profile.get(name, [])
        if len(pings) != 6 or len(portrows) != 12:
            problems.append(f"{name}: expected 6 probes and 12 ports; got {len(pings)} and {len(portrows)}")
        if len({(r.get("source_node_id"), r.get("target_node_id")) for r in pings}) != len(pings):
            problems.append(f"{name}: duplicate host-pair probes")
        if len({(r.get("link_id"), r.get("node_id")) for r in portrows}) != len(portrows):
            problems.append(f"{name}: duplicate port samples")
        unreachable = sum(r.get("reachable") == "0" for r in pings)
        if unreachable:
            warnings.append(f"{name}: {unreachable} unreachable probes")
        if any(r.get("admin_up_before") != "1" or r.get("admin_up_after") != "1" for r in portrows):
            problems.append(f"{name}: an interface was not administratively UP")
        if any(number(r.get(c)) is None or number(r.get(c)) < 0 for r in portrows for c in COUNTERS):
            problems.append(f"{name}: invalid or negative port counter delta")
        for r in portrows:
            if number(r.get("duration_s")) is None or number(r["duration_s"]) <= 0:
                problems.append(f"{name}: invalid port-counter sample duration")
                break

        server_nic = next((r for r in portrows if r.get("link_id") == "L4" and r.get("node_id") == "SRV-LOCAL"), None)
        sender_nic = next((r for r in portrows if r.get("link_id") == "L5" and r.get("node_id") == "PC-SHOP"), None)
        def nic_mbps(record, count):
            if not record:
                return None
            delta, elapsed = number(record.get(count)), number(record.get("duration_s"))
            if delta is None or elapsed is None or elapsed <= 0:
                return None
            return 8 * delta / elapsed / 1e6
        rx_host = nic_mbps(server_nic, "rx_bytes_delta")
        tx_host = nic_mbps(sender_nic, "tx_bytes_delta")
        if rx_host is None or tx_host is None:
            problems.append(f"{name}: source or destination host NIC statistics missing")

        receiver, source = None, "not applicable"
        if offered and offered > 0:
            filename = pilot / f"iperf3_{name}.json"
            if not filename.is_file():
                problems.append(f"{name}: missing {filename.name}")
            else:
                raw = json.loads(filename.read_text(encoding="utf-8-sig"))
                receiver, source = find_receiver_rate(raw)
                if receiver is None:
                    warnings.append(f"{name}: no explicit iperf3 receiver-role measurement; see raw JSON")
                    detail.append(f"- `{name}` raw iperf3 end sections: `{', '.join(raw.get('end', {}).keys())}`")
                    streams = raw.get("end", {}).get("streams", [])
                    if streams:
                        detail.append(f"  - first end.streams entry keys: `{', '.join(streams[0].keys())}`")
                        for typ in ("udp", "sender", "receiver"):
                            ent = streams[0].get(typ, {})
                            if isinstance(ent, dict):
                                detail.append(f"  - `{typ}` sender flag: `{ent.get('sender', 'absent')}`")
                elif receiver <= 0:
                    warnings.append(f"{name}: receiver reported zero throughput")
        loads.append((offered, rx_host))
        def fmt(v):
            return f"{v:.3f}" if v is not None else "N/A"
        table.append(f"| {name} | {fmt(offered)} | {fmt(receiver)} | {source} | {fmt(tx_host)} | {fmt(rx_host)} | {unreachable} |")
    ordered = [(a, b) for a, b in loads if a is not None and a > 0 and b is not None]
    ordered.sort()
    if len(ordered) > 1 and any(ordered[i][1] <= ordered[i-1][1] for i in range(1, len(ordered))):
        warnings.append("Destination host measured NIC ingress is not increasing with offered UDP load")

    status = "FAIL" if problems else "PASS"
    report = [
        "# SmartMall SMALL — background traffic pilot audit", "",
        f"- Pilot: `{expid}`", f"- Source folder: `{pilot}`",
        f"- Data integrity: **{status}**", f"- Observations: **{len(probes)} ICMP**, **{len(ports)} port deltas**", "",
        "## Traffic validation", "",
        "| Profile | Offered Mb/s | iperf3 verified receiver Mb/s | Verification source | Host PC-SHOP egress Mb/s | Host SRV-LOCAL ingress Mb/s | Unreachable ICMP |",
        "|---|---:|---:|---|---:|---:|---:|", *table, "",
        "**Meaning:** host egress / ingress are byte-counter rates during the ICMP sampling window. They are *not* iperf3 UDP goodput; ",
        "they include protocol overhead, other packets, and potentially background activity. The `end.sum` value without an explicit receiver indicator is **not** accepted as confirmed received goodput.", "",
        "## Warnings", "", *([f"- {x}" for x in warnings] if warnings else ["- None"]), "",
        "## Integrity errors", "", *([f"- {x}" for x in problems] if problems else ["- None"]), "",
        "## Raw iperf3 shape details", "", *(detail or ["- All active profiles had an explicit receiver rate."]), "",
        "## Scientific limitations", "",
        "- No link failure was injected; this is a controlled load-generation smoke test.",
        "- ICMP probes are sequential; each profile has only six host-pair observations.",
        "- Rates and RTT differences are descriptive only, not estimates of load-induced congestion.",
        "- Do not combine this load pilot with labeled LINK_FAILURE campaigns as though its profiles were fault examples.", "",
    ]
    output = ROOT / "docs" / "history" / "small_v1" / f"small_load_pilot_audit_{expid}.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))
    print(f"Report: {output}")
    if problems:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
